// Deterministic, offline merge. Existing IDs and original fields remain intact.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const write=(p,s)=>fs.writeFileSync(path.join(root,p),s);
const key=s=>s.normalize('NFKC').toLowerCase().replace(/\s+/g,' ').trim();
const ranges={1:[14,25],2:[26,37],3:[42,53],4:[54,65]};
const legacy=JSON.parse(read('tests/fixtures/legacy-vocabulary.json'));
const words=structuredClone(legacy);
const lookup=new Map(words.map(w=>[key(w.en),w]));
for(const w of words){
  for(const alias of w.aliases)if(!lookup.has(key(alias)))lookup.set(key(alias),w);
  w.units=[w.unit];w.unitPages={[w.unit]:ranges[w.unit]};w.sourceEntries=[];
}
const additions=new Map();
for(const [i,line] of read('data/additions.tsv').trim().split('\n').entries()){
  const columns=line.split('|');
  if(columns.length!==6||columns.some(s=>!s.trim()))throw Error(`Invalid additions row ${i+1}`);
  const [en,kk,pos,example,exampleRu,exampleKk]=columns;
  if(additions.has(key(en)))throw Error(`Duplicate addition: ${en}`);
  additions.set(key(en),{kk:kk.split(';'),pos,example,exampleRu,exampleKk});
}
const rows=[];let unit;
for(const line of read('data/source-vocabulary.md').split('\n')){
  const match=line.match(/^## Unit (\d)/);if(match)unit=Number(match[1]);
  if(line.startsWith('| ')&&!line.startsWith('| English')){
    const [en,ru]=line.split('|').slice(1,3).map(s=>s.trim());
    if(!ranges[unit])throw Error('Unknown source unit');
    rows.push({unit,en,ru});
  }
}
const aliases={
 'information technology (IT)':['information technology','IT'],
 'artificial intelligence (AI)':['artificial intelligence','AI'],
 'fly (insect)':['fly'],
 'practise':['practice'], 'emphasise':['emphasize'], 'modelling':['modeling'],
 'recognise':['recognize'], 'organise':['organize'], 'categorise':['categorize'],
 'stabilise':['stabilize'], 'summarise':['summarize'],
 'consumer behaviour':['consumer behavior'], 'labour force':['labor force'],
 'dehumanization':['dehumanisation'], 'civilization':['civilisation']
};
const counters=Object.fromEntries(Object.keys(ranges).map(u=>[u,Math.max(0,...legacy.filter(w=>w.unit===Number(u)).map(w=>Number(w.id.split('-')[1])))]));
const used=new Set();
// Add Unit 4 first, then fill gaps in Units 1–3. Membership is collected separately.
for(const row of [...rows].sort((a,b)=>[4,1,2,3].indexOf(a.unit)-[4,1,2,3].indexOf(b.unit))){
  let w=lookup.get(key(row.en));
  if(!w){
    const content=additions.get(key(row.en));if(!content)throw Error(`Missing content: ${row.en}`);
    used.add(key(row.en));
    const ru=(row.en==='flower-eating beetle'?[row.ru]:row.ru.split(/;\s*|,\s*/)).map(s=>s.trim()).filter(Boolean);
    // Parenthetical explanations stay in sourceEntries; accept the short translation too.
    for(const value of [...ru]){const plain=value.replace(/\s*\([^)]*\)/g,'').trim();if(plain&&!ru.includes(plain))ru.push(plain);}
    w={id:`u${row.unit}-${String(++counters[row.unit]).padStart(3,'0')}`,unit:row.unit,en:row.en,ru,page:null,pageRange:ranges[row.unit],...content,priority:false,note:'',noteKk:'',aliases:aliases[row.en]||[],units:[],unitPages:{},sourceEntries:[]};
    words.push(w);lookup.set(key(row.en),w);
  }
  if(!w.units.includes(row.unit))w.units.push(row.unit);
  w.unitPages[row.unit]=ranges[row.unit];
  w.sourceEntries.push({...row,pageRange:ranges[row.unit]});
}
if(used.size!==additions.size)throw Error('Unused additions: '+[...additions.keys()].filter(k=>!used.has(k)).join(', '));
for(const w of words){w.units.sort();w.sourceEntries.sort((a,b)=>a.unit-b.unit||a.en.localeCompare(b.en));}
const json=JSON.stringify(words,null,2)+'\n';
write('vocabulary.json',json);
write('assets/words.js','/* Generated by scripts/build-vocabulary.mjs; do not edit directly. */\nwindow.LEXI_WORDS = '+json.trimEnd()+';\n');
const report={baseCommit:'b811d5a7ad63b79642deec71c7892b7c5ad464eb',sourceRows:rows.length,legacyCards:legacy.length,addedCards:words.length-legacy.length,totalCards:words.length,sourceRowsByUnit:{},cardsByUnit:{},multiUnitCards:words.filter(w=>w.units.length>1).length,sourceMatches:rows.map(r=>({...r,id:lookup.get(key(r.en)).id}))};
for(const u of Object.keys(ranges)){report.sourceRowsByUnit[u]=rows.filter(r=>r.unit===Number(u)).length;report.cardsByUnit[u]=words.filter(w=>w.units.includes(Number(u))).length;}
write('data/merge-report.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({...report,sourceMatches:undefined},null,2));
// Keep the original source merge reproducible, then attach the verified Units 3–5 course.
await import('./build-readings.mjs');
