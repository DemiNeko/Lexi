// Source-linked curriculum layered onto the backwards-compatible vocabulary.
// Reading pages refer to the passage, never an inferred location of an individual term.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const write=(p,s)=>fs.writeFileSync(path.join(root,p),s);
const words=JSON.parse(read('vocabulary.json'));
const readings=JSON.parse(read('data/readings.json'));
const key=s=>s.toLowerCase().trim();
const lookup=new Map(words.map(w=>[key(w.en),w]));
const ranges={3:[42,53],4:[54,65],5:[70,81]};
const identities=JSON.parse(read('data/reading-identities.json'));
if(new Set(Object.values(identities)).size!==Object.keys(identities).length)throw Error('Duplicate reading identity');
const content=new Map(read('data/reading-additions.tsv').trimEnd().split('\n').map((line,i)=>{
 const cols=line.split('|');if(cols.length!==8||cols.slice(0,7).some(s=>!s.trim()))throw Error(`Invalid reading addition ${i+1}`);
 const [en,ru,kk,pos,example,exampleRu,exampleKk,aliases]=cols;
 return [key(en),{en,ru:ru.split(';'),kk:kk.split(';'),pos,example,exampleRu,exampleKk,aliases:aliases?aliases.split(';'):[]}];
}));
// Same lexical sense, different phrasing: one new card, both accepted answers.
const canonical=new Map([['living standard','standard of living']]);
for(const w of words){w.readings=[];w.readingUnits=[];}
for(const r of readings){
 r.wordIds=[];
 for(const term of r.terms){
  const canonicalTerm=canonical.get(key(term))||term;
  let w=lookup.get(key(canonicalTerm));
  if(!w){
   const entry=content.get(key(canonicalTerm));if(!entry)throw Error('Missing content: '+term);
   if(!identities[entry.en])throw Error('Assign a permanent identity for '+entry.en);
   w={id:identities[entry.en],unit:r.unit,...entry,page:null,pageRange:ranges[r.unit],priority:true,note:'',noteKk:'',units:[r.unit],unitPages:{[r.unit]:ranges[r.unit]},sourceEntries:[],readings:[],readingUnits:[]};
   words.push(w);lookup.set(key(canonicalTerm),w);
  }
  if(canonicalTerm!==term&&!w.aliases.includes(term))w.aliases.push(term);
  if(!r.wordIds.includes(w.id))r.wordIds.push(w.id);
  if(!w.readings.includes(r.id))w.readings.push(r.id);
  if(!w.readingUnits.includes(r.unit))w.readingUnits.push(r.unit);
  if(!w.units.includes(r.unit))w.units.push(r.unit);
  w.unitPages[r.unit]=ranges[r.unit];
 }
}
for(const [term,aliases] of Object.entries({'information explosion':['explosion of information'],'online':['on-line'],'online travel agency':['on-line travel agency']})){const w=lookup.get(key(term));for(const a of aliases)if(!w.aliases.includes(a))w.aliases.push(a);}
for(const w of words){w.units.sort();w.readingUnits.sort();}
for(const [id,fields] of Object.entries(JSON.parse(read('data/content-corrections.json')))){const w=words.find(w=>w.id===id);if(!w)throw Error('Unknown correction ID '+id);Object.assign(w,fields);}
const json=JSON.stringify(words,null,2)+'\n';
write('vocabulary.json',json);
write('assets/words.js','/* Generated by scripts/build-vocabulary.mjs; do not edit directly. */\nwindow.LEXI_WORDS = '+json.trimEnd()+';\nwindow.LEXI_READINGS = '+JSON.stringify(readings.map(({terms,...r})=>r),null,2)+';\n');
const active=words.filter(w=>w.readings.length);
const report={baseCommit:'b811d5a7ad63b79642deec71c7892b7c5ad464eb',previousCards:759,newCards:words.length-759,totalStoredCards:words.length,activeCards:active.length,archivedCards:words.length-active.length,readingCount:readings.length,cardsByUnit:Object.fromEntries([3,4,5].map(u=>[u,active.filter(w=>w.readingUnits.includes(u)).length])),multiUnitCards:active.filter(w=>w.readingUnits.length>1).length,readingMatches:readings};
write('data/reading-report.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({...report,readingMatches:undefined},null,2));
